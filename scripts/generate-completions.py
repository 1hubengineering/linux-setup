#!/usr/bin/env python3
"""Regenerate checked-in completions from the public commands' argparse definitions."""
from pathlib import Path
import subprocess
import os
import sys

ROOT = Path(__file__).resolve().parents[1]
COMMANDS = ['install.sh', 'uninstall.sh'] + ['bin/' + p.name for p in sorted((ROOT / 'bin').iterdir()) if p.is_file()]
ALIASES = {'theme-manager': ['theme'], 'git-profile': ['github'], 'skill-manager': ['skills'], 'dev-tools': ['devtools'], 'shell-toggle': ['shell'], 'shell-default': ['default-shell'], 'linux-setup-update': ['update']}


def generate():
    target = ROOT / 'config/completions'
    target.mkdir(parents=True, exist_ok=True)
    environment = dict(os.environ, LINUX_SETUP_BUILD_CLI='1')
    help_dir = ROOT / 'config/cli-help'
    help_dir.mkdir(parents=True, exist_ok=True)
    for path in COMMANDS:
        output = subprocess.run([str(ROOT / path), '--help'], env=environment, capture_output=True, text=True, check=True).stdout
        (help_dir / (Path(path).name + '.txt')).write_text(output)
    for shell in ('bash', 'zsh', 'fish'):
        parts = ['# Generated by scripts/generate-completions.py; do not edit by hand.\n']
        for path in COMMANDS:
            args = [str(ROOT / path), '--completion', shell]
            result = subprocess.run(args, env=environment, capture_output=True, text=True, check=True)
            script = result.stdout
            if not script.strip():
                raise RuntimeError(f'{path} returned no {shell} completion script')
            parts.append(script)
            command = Path(path).name
            for alias in ALIASES.get(command, []):
                if shell == 'bash':
                    parts.append(f'complete -o default -F _linux_setup_{command.replace("-", "_")} {alias}\n')
                elif shell == 'zsh':
                    parts.append(f'compdef _linux_setup_{command.replace("-", "_")} {alias}\n')
                else:
                    parts.append(f'complete -c {alias} -w {command}\n')
        (target / ('linux-setup.' + shell)).write_text('\n'.join(parts))


if __name__ == '__main__':
    generate()
